"""One safe error envelope for API errors, including framework errors."""

from http import HTTPStatus
import re
from uuid import UUID

from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException

from ..common.errors import AppError, public_error
from ..common.request_context import log_failure
from ..privacy.deletion import DeletionError
from ..workflows.concurrency import RequestErased


DELETION_ERRORS = {
    'not_found': (404, '记录或删除预览、任务不存在，请刷新。'),
    'invalid_target': (422, '只能删除健康事件或长期信息。'),
    'request_mismatch': (409, '同一个删除请求编号不能用于不同目标。'),
    'scope_changed': (409, '清理范围已变化，请重新查看影响范围。'),
    'preview_required': (428, '请先查看并确认删除范围。'),
}
PREVIEW_REASONS = frozenset({
    '历史数据缺少完整来源关系，需要扩大清理范围；可独立验证的健康记录仅清除原文副本，不能验证的记录和长期信息会一并删除。',
    '部分共享原文无法独立验证，相关记录需要一并删除。',
})
PREVIEW_COUNT_KEYS = frozenset({
    f'{kind}:{action}'
    for kind in ('event', 'fact', 'workflow', 'message', 'plan', 'insight', 'review',
                 'notification', 'operation', 'summary', 'checkpoint', 'meta', 'receipt')
    for action in ('delete', 'minimize', 'keep_targets')
}) | {'receipts', 'resume_attempts'}


def safe_preview(preview):
    if not isinstance(preview, dict):
        return None
    # Preview IDs/types/counts are protocol metadata; no arbitrary nested content.
    result = {}
    for key in ('target_id', 'preview_id'):
        value = preview.get(key)
        # Chat facts use <workflow UUID>:fact[:action index], in addition to UUIDs.
        suffix = r'(?::fact(?::[0-9]{1,2})?)?' if key == 'target_id' else ''
        if not isinstance(value, str) or not re.fullmatch(r'[a-fA-F0-9-]{36}' + suffix, value):
            return None
        try:
            UUID(value[:36])
        except ValueError:
            return None
        result[key] = value
    if preview.get('target_type') not in ('event', 'fact'):
        return None
    if preview.get('scope') not in ('dependencies', 'shared_source', 'legacy_context'):
        return None
    result.update(target_type=preview['target_type'], scope=preview['scope'])
    counts = preview.get('counts', {})
    result['counts'] = {key: value for key, value in counts.items()
                        if key in PREVIEW_COUNT_KEYS
                        and type(value) is int and value >= 0} if isinstance(counts, dict) else {}
    reasons = preview.get('reasons', [])
    result['reasons'] = [reason for reason in reasons if isinstance(reason, str)
                         and reason in PREVIEW_REASONS] if isinstance(reasons, list) else []
    return result


def error_response(request, status, code, detail, **extra):
    correlation = request.state.request_id
    log_failure(code, correlation_id=correlation, status=status)
    response = JSONResponse(status_code=status, content={
        'detail': detail, 'code': code, 'request_id': correlation, **extra,
    }, headers={'X-Request-ID': correlation})
    if status == 500:
        request.state.safe_error_response = True
    return response


async def application_error(request, error):
    code, spec = public_error(error)
    return error_response(request, spec.status, code, spec.message)


async def validation_error(request, error):
    # Only root request schema names may be shown. Unknown keys/values, ctx and
    # Pydantic messages can contain health data and are deliberately discarded.
    route = request.scope.get('route')
    body_field = getattr(route, 'body_field', None)
    fields = getattr(getattr(body_field, 'type_', None), 'model_fields', {})
    types = {'missing': 'required', 'extra_forbidden': 'unknown_field',
             'json_invalid': 'invalid_json'}
    issues = []
    for item in error.errors()[:20]:
        location = item.get('loc', ())
        name = location[1] if len(location) == 2 and location[0] == 'body' else None
        issues.append({'field': name if isinstance(name, str) and name in fields else 'request',
                       'code': types.get(item.get('type'), 'invalid_value')})
    return error_response(request, 422, 'request_validation_failed',
                          '请求参数不合法，请检查后重试。', errors=issues)


async def http_error(request, error):
    status = error.status_code
    try:
        title = HTTPStatus(status).phrase
    except ValueError:
        return await application_error(request, error)
    response = error_response(request, status, f'http_{status}', f'请求失败：{title}。')
    if status == 405:
        # Allow is generated by the router, never forward arbitrary error headers.
        allow = (error.headers or {}).get('Allow', '')
        methods = [value.strip() for value in allow.split(',')]
        if methods and all(value in {'GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'} for value in methods):
            response.headers['Allow'] = ', '.join(methods)
    return response


async def deletion_error(request, error):
    spec = DELETION_ERRORS.get(error.code)
    if spec is None or spec[0] != error.status:
        return await application_error(request, error)
    return error_response(request, spec[0], error.code, spec[1], preview=safe_preview(error.preview))


async def erased_error(request, error):
    return error_response(request, 410, 'request_erased',
                          '此请求的相关内容已删除，请使用新请求重新输入。')


def register_error_handlers(app):
    for kind, handler in (
        (AppError, application_error), (Exception, application_error),
        (RequestValidationError, validation_error), (HTTPException, http_error),
        (DeletionError, deletion_error), (RequestErased, erased_error),
    ):
        app.add_exception_handler(kind, handler)
